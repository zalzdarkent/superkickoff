/// Converts ISO-3166 alpha-2 country code to emoji flag (e.g. 'JP' -> '🇯🇵', 'ID' -> '🇮🇩').
/// Can also fallback to resolve via [name] or [countryId].
String countryFlag(Object? iso2, {int? countryId, String? name}) {
  if (countryId == 185 || name == 'Inggris' || name == 'England' || name == 'Inglaterra') {
    return '🏴󠁧󠁢󠁥󠁮󠁧󠁿';
  }
  if (countryId == 249 || name == 'Skotlandia' || name == 'Scotland' || name == 'Escocia') {
    return '🏴󠁧󠁢󠁳󠁣󠁴󠁿';
  }
  if (countryId == 250 || name == 'Wales' || name == 'Gales') {
    return '🏴󠁧󠁢󠁷󠁬󠁳󠁿';
  }
  if (countryId == 251 ||
      name == 'Irlandia Utara' ||
      name == 'Northern Ireland' ||
      name == 'Irlanda del Norte') {
    return '🇬🇧';
  }

  String code = '${iso2 ?? ''}'.trim().toUpperCase();
  if (code.length != 2 && name != null && name.isNotEmpty) {
    code = _nameToIso[name.trim()] ?? _nameToIso[displayCountryName(name.trim(), '')] ?? '';
  }
  if (code.length != 2) return '';
  final int first = code.codeUnitAt(0);
  final int second = code.codeUnitAt(1);
  if (first < 0x41 || first > 0x5A || second < 0x41 || second > 0x5A) {
    return '';
  }
  return String.fromCharCodes(<int>[
    0x1F1E6 + first - 0x41,
    0x1F1E6 + second - 0x41,
  ]);
}

